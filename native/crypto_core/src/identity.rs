//! Persistent Noise X25519 identity for the production BeChat application.
//!
//! Rust owns the static identity private seed end to end:
//!
//! * [`generate_identity_seed`] creates a 32-byte X25519 private seed using
//!   the pinned Snow resolver (the same code path as the validated spike).
//! * [`derive_identity_public_key`] derives the 32-byte public key with
//!   Snow's Curve25519 DH implementation. No custom curve code exists here.
//! * [`install_identity`] validates seed length, expected public-key hex and
//!   public/private correspondence *before* storing the seed in process
//!   memory, wrapped by `zeroize`.
//! * [`clear_installed_identity`] drops the installed identity.
//! * [`installed_public_key_hex`] reports only public information.
//!
//! Private seed bytes never leave this module except through the narrow JNI
//! boundary in the `bechat_crypto` crate, where they travel directly between
//! Rust and Kotlin. They must never be returned to Dart.
//!
//! All error strings are fixed, non-secret messages: they are safe to surface
//! through the Kotlin boundary and never contain key material.

use std::sync::{Mutex, OnceLock};

use snow::params::DHChoice;
use snow::resolvers::{CryptoResolver, DefaultResolver};
use snow::Builder;
use zeroize::Zeroizing;

use crate::NOISE_XX_PATTERN;

/// Length in bytes of the Noise static private seed (X25519 scalar).
pub const IDENTITY_SEED_LENGTH: usize = 32;

/// Length in bytes of the Noise static public key (X25519 point).
pub const IDENTITY_PUBLIC_KEY_LENGTH: usize = 32;

struct InstalledIdentity {
    // The installed seed is stored on purpose: installing an identity means
    // holding the validated private material ready for the Noise session
    // engine (`session` module), which reads it through the crate-internal
    // `installed_identity_key_material` accessor. `Zeroizing` clears it when
    // the identity is replaced, cleared, or the process exits.
    private_key: Zeroizing<Vec<u8>>,
    public_key: Vec<u8>,
}

static INSTALLED: OnceLock<Mutex<Option<InstalledIdentity>>> = OnceLock::new();

fn installed() -> &'static Mutex<Option<InstalledIdentity>> {
    INSTALLED.get_or_init(|| Mutex::new(None))
}

/// Generates a fresh Noise-compatible static identity seed.
///
/// The seed is generated by Snow's key generation for the production XX
/// suite. Callers must treat the returned bytes as secret key material.
pub fn generate_identity_seed() -> Result<Vec<u8>, String> {
    let params = NOISE_XX_PATTERN
        .parse()
        .map_err(|_| "invalid Noise parameters")?;
    let keypair = Builder::new(params)
        .generate_keypair()
        .map_err(|_| "identity key generation failed")?;
    if keypair.private.len() != IDENTITY_SEED_LENGTH {
        return Err("invalid generated identity key length".into());
    }
    Ok(keypair.private)
}

/// Derives the public key for a 32-byte X25519 private seed.
///
/// Fails closed on any seed length other than 32 bytes.
pub fn derive_identity_public_key(seed: &[u8]) -> Result<Vec<u8>, String> {
    if seed.len() != IDENTITY_SEED_LENGTH {
        return Err("invalid identity seed length".into());
    }
    let mut dh = DefaultResolver
        .resolve_dh(&DHChoice::Curve25519)
        .ok_or("X25519 implementation unavailable")?;
    dh.set(seed);
    let public_key = dh.pubkey();
    if public_key.len() != IDENTITY_PUBLIC_KEY_LENGTH {
        return Err("invalid identity public key length".into());
    }
    Ok(public_key.to_vec())
}

/// Derives the public key for a seed and returns it as lowercase hex.
///
/// Shared by the JNI layer so only one hex-encoding implementation exists.
pub fn derive_identity_public_key_hex(seed: &[u8]) -> Result<String, String> {
    derive_identity_public_key(seed).map(hex::encode)
}

/// Installs a seed after validating it against the expected public key.
///
/// The seed is rejected unless:
///
/// * it is exactly [`IDENTITY_SEED_LENGTH`] bytes,
/// * the expected public key is well-formed 32-byte hex,
/// * the public key derived from the seed equals the expected public key.
///
/// On success the previously installed identity (if any) is replaced.
pub fn install_identity(seed: &[u8], expected_public_key_hex: &str) -> Result<(), String> {
    let public_key = derive_identity_public_key(seed)?;
    let expected = decode_public_key(expected_public_key_hex)?;
    if public_key != expected {
        return Err("identity public key mismatch".into());
    }

    let mut guard = installed()
        .lock()
        .map_err(|_| "identity store unavailable")?;
    *guard = Some(InstalledIdentity {
        private_key: Zeroizing::new(seed.to_vec()),
        public_key,
    });
    Ok(())
}

/// Removes the installed identity from process memory (best effort).
pub fn clear_installed_identity() {
    if let Ok(mut guard) = installed().lock() {
        *guard = None;
    }
}

/// Returns the installed public key as lowercase hex, or `None`.
///
/// This is the only status query the native surface exposes; there is
/// deliberately no accessor for the private seed.
pub fn installed_public_key_hex() -> Result<Option<String>, String> {
    let guard = installed()
        .lock()
        .map_err(|_| "identity store unavailable")?;
    Ok(guard
        .as_ref()
        .map(|identity| hex::encode(&identity.public_key)))
}

/// Crate-internal accessor handing the installed seed to the session engine.
///
/// Returns a `Zeroizing` clone of the private seed alongside the public key.
/// The clone is cleared on drop by the caller (the session module), and the
/// original stays protected inside the installed identity. This function is
/// deliberately `pub(crate)`: no JNI export, no public API and no path to
/// Dart ever touches it. Fails when no identity is installed.
pub(crate) fn installed_identity_key_material() -> Result<(Zeroizing<Vec<u8>>, Vec<u8>), String> {
    let guard = installed()
        .lock()
        .map_err(|_| "identity store unavailable")?;
    let identity = guard.as_ref().ok_or("no identity is installed")?;
    Ok((
        Zeroizing::new(identity.private_key.to_vec()),
        identity.public_key.clone(),
    ))
}

/// Decodes a 32-byte lowercase-hex X25519 public key into raw bytes.
///
/// Shared by the identity installer and the session engine's pin validation;
/// `pub(crate)` so only this module parses key encodings.
pub(crate) fn decode_public_key(value: &str) -> Result<Vec<u8>, String> {
    let bytes = hex::decode(value).map_err(|_| "invalid identity public key")?;
    if bytes.len() != IDENTITY_PUBLIC_KEY_LENGTH {
        return Err("invalid identity public key length".into());
    }
    Ok(bytes)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::NOISE_XX_PATTERN;
    use snow::Builder;
    use std::thread;

    #[test]
    fn generate_identity_seed_returns_32_distinct_bytes() {
        let first = generate_identity_seed().expect("seed generation");
        let second = generate_identity_seed().expect("seed generation");
        assert_eq!(first.len(), IDENTITY_SEED_LENGTH);
        assert_eq!(second.len(), IDENTITY_SEED_LENGTH);
        assert_ne!(first, second, "two generations must not collide");
    }

    #[test]
    fn derive_identity_public_key_rejects_invalid_seed_lengths() {
        for length in [0usize, 1, 31, 33, 64] {
            let seed = vec![0u8; length];
            assert!(
                derive_identity_public_key(&seed).is_err(),
                "seed length {length} must be rejected"
            );
        }
    }

    #[test]
    fn derive_matches_snow_keypair_public_key() {
        let params = NOISE_XX_PATTERN.parse().expect("XX params");
        let keypair = Builder::new(params).generate_keypair().expect("keypair");
        let derived = derive_identity_public_key(&keypair.private).expect("derive");
        assert_eq!(derived, keypair.public);
        assert_eq!(derived.len(), IDENTITY_PUBLIC_KEY_LENGTH);
    }

    #[test]
    fn derive_hex_helper_is_lowercase_and_matches_raw_derivation() {
        let seed = generate_identity_seed().expect("seed");
        let hex_key = derive_identity_public_key_hex(&seed).expect("derive hex");
        let raw_key = derive_identity_public_key(&seed).expect("derive");
        assert_eq!(hex_key, hex::encode(&raw_key));
        assert_eq!(hex_key.len(), IDENTITY_PUBLIC_KEY_LENGTH * 2);
        assert!(hex_key
            .chars()
            .all(|c| c.is_ascii_digit() || ('a'..='f').contains(&c)));
        assert!(derive_identity_public_key_hex(&[0u8; 31]).is_err());
    }

    /// Single test covering the full installed-identity lifecycle. It is kept
    /// as one test because the installed identity lives in process-wide static
    /// state that would otherwise race between parallel test threads.
    #[test]
    fn installed_identity_lifecycle_validates_and_clears() {
        // Start from a clean slate.
        clear_installed_identity();
        assert_eq!(installed_public_key_hex().expect("query"), None);

        // Wrong seed length is rejected and installs nothing.
        assert!(install_identity(&[0u8; 31], &"00".repeat(32)).is_err());
        assert_eq!(installed_public_key_hex().expect("query"), None);

        let seed = generate_identity_seed().expect("seed");
        let public_key = derive_identity_public_key(&seed).expect("derive");
        let public_hex = hex::encode(&public_key);

        // Malformed expected public key is rejected.
        assert!(install_identity(&seed, "not-hex").is_err());
        assert!(install_identity(&seed, &"00".repeat(31)).is_err());
        assert_eq!(installed_public_key_hex().expect("query"), None);

        // A mismatched but well-formed public key is rejected and the
        // previously installed identity (none) stays untouched.
        let wrong_hex = if public_hex == "11".repeat(32) {
            "22".repeat(32)
        } else {
            "11".repeat(32)
        };
        assert!(install_identity(&seed, &wrong_hex).is_err());
        assert_eq!(installed_public_key_hex().expect("query"), None);

        // The correct pair installs and reports its public key.
        install_identity(&seed, &public_hex).expect("install");
        assert_eq!(
            installed_public_key_hex().expect("query"),
            Some(public_hex.clone())
        );

        // A rejected install must not clobber an established identity.
        assert!(install_identity(&seed, &wrong_hex).is_err());
        assert_eq!(
            installed_public_key_hex().expect("query"),
            Some(public_hex.clone())
        );

        clear_installed_identity();
        assert_eq!(installed_public_key_hex().expect("query"), None);
    }

    /// Concurrent installs must be serialized by the internal lock: every
    /// call either succeeds or fails cleanly, and exactly one identity
    /// remains installed afterwards.
    #[test]
    fn concurrent_installs_are_serialized() {
        clear_installed_identity();
        let seeds: Vec<(Vec<u8>, String)> = (0..8)
            .map(|_| {
                let seed = generate_identity_seed().expect("seed");
                let public = hex::encode(derive_identity_public_key(&seed).expect("derive"));
                (seed, public)
            })
            .collect();

        let handles: Vec<_> = seeds
            .iter()
            .map(|(seed, public)| {
                let seed = seed.clone();
                let public = public.clone();
                thread::spawn(move || install_identity(&seed, &public).is_ok())
            })
            .collect();
        for handle in handles {
            // A panicked thread would surface here as a join error.
            handle.join().expect("install thread must not panic");
        }

        let installed_hex = installed_public_key_hex()
            .expect("query")
            .expect("one identity must remain installed");
        assert!(
            seeds.iter().any(|(_, public)| *public == installed_hex),
            "installed identity must be one of the generated identities"
        );
        clear_installed_identity();
    }
}
