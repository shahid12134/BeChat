package com.bechat.bechat

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.io.ByteArrayOutputStream
import java.io.File
import java.io.FileOutputStream
import java.security.GeneralSecurityException
import java.security.KeyStore
import java.security.KeyStoreException
import java.security.MessageDigest
import java.security.UnrecoverableKeyException
import java.util.Locale
import java.util.TimeZone
import java.text.SimpleDateFormat
import java.util.Date
import javax.crypto.AEADBadTagException
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Fixed, non-secret failure raised by the production identity store.
 *
 * Messages are constants: no seed bytes, wrapping keys, ciphertext, file
 * contents or provider exception detail may ever flow through them.
 */
open class IdentityStoreException(message: String) : Exception(message)

/** The public identity metadata file is missing when a blob is present, or malformed. */
class MetadataInvalidException(message: String) : IdentityStoreException(message)

/** Public metadata exists but the encrypted private-key blob does not. */
class BlobMissingException(message: String) : IdentityStoreException(message)

/** The encrypted blob is structurally invalid or failed authenticated decryption. */
class BlobCorruptException(message: String) : IdentityStoreException(message)

/** The encrypted blob declares an envelope version or algorithm this build cannot read. */
class BlobUnsupportedException(message: String) : IdentityStoreException(message)

/** The Android Keystore wrapping key is missing, invalidated or unusable. */
class KeystoreKeyUnavailableException(message: String) : IdentityStoreException(message)

/**
 * Non-secret public identity metadata.
 *
 * This is the type a later phase can back with SQLite instead of the metadata
 * file without touching the cryptographic core: the store is the only place
 * that knows where the metadata lives.
 */
data class IdentityMetadata(
    val publicKeyHex: String,
    val algorithm: String,
    val createdAt: String,
)

/**
 * Production Android storage for the Noise static identity private seed.
 *
 * The seed itself never lands here in plaintext and never reaches Dart. This
 * class:
 *
 * * creates/uses a non-exportable AES-256-GCM wrapping key in Android Keystore
 *   under the production alias [KEY_ALIAS];
 * * wraps the seed with authenticated encryption, binding the production
 *   envelope header, the algorithm and the expected public key as AES-GCM
 *   additional authenticated data;
 * * persists the wrapped envelope atomically under the application's
 *   `noBackupFilesDir` so it cannot be restored without its Keystore key;
 * * persists non-secret public metadata (public key, algorithm, creation time)
 *   in a separate, strictly validated file.
 *
 * ## Blob format (`BCID` envelope, version 1)
 *
 * Byte offsets, all lengths fixed:
 *
 * | Offset | Length | Field |
 * | --- | --- | --- |
 * | 0 | 4 | magic `B`, `C`, `I`, `D` (`0x42 0x43 0x49 0x44`) |
 * | 4 | 1 | envelope version (`1`) |
 * | 5 | 1 | algorithm id (`1` = AES-256-GCM, 128-bit tag) |
 * | 6 | 1 | IV length (`12`) |
 * | 7 | 1 | seed length (`32`) |
 * | 8 | 12 | IV / nonce, generated by Android Keystore randomized encryption |
 * | 20 | 48 | ciphertext (32 bytes of seed) followed by the 16-byte GCM tag |
 *
 * Total length is exactly 68 bytes. This is a distinct production format: the
 * spike's `BCSI`/version-1 envelope is a different layout and is not
 * reinterpreted here. AAD is the 8-byte header followed by the 64 ASCII
 * characters of the lowercase-hex public key, so altering the metadata public
 * key (or the algorithm/version bytes) makes authenticated decryption fail.
 */
class IdentityBlobStore(context: Context) {
    private companion object {
        const val KEYSTORE_PROVIDER = "AndroidKeyStore"

        /** Production-specific Keystore alias (distinct from the spike's). */
        const val KEY_ALIAS = "bechat_identity_wrap_v1"

        /** Production-specific no-backup directory under `noBackupFilesDir`. */
        const val DIRECTORY = "bechat_identity"
        const val BLOB_FILE = "identity.blob"
        const val BLOB_TEMP_FILE = "identity.blob.tmp"
        const val METADATA_FILE = "identity.meta"
        const val METADATA_TEMP_FILE = "identity.meta.tmp"

        const val METADATA_HEADER = "bechat-identity-meta/1"
        const val IDENTITY_ALGORITHM = "noise-x25519-chachapoly-sha256"
        const val MAX_CREATED_AT_LENGTH = 40

        val MAGIC = byteArrayOf(0x42, 0x43, 0x49, 0x44)
        const val ENVELOPE_VERSION = 1
        const val ALGORITHM_AES_256_GCM = 1
        const val IV_LENGTH = 12
        const val SEED_LENGTH = 32
        const val TAG_LENGTH = 16
        const val HEADER_LENGTH = 8
        const val BLOB_LENGTH = HEADER_LENGTH + IV_LENGTH + SEED_LENGTH + TAG_LENGTH

        val PUBLIC_KEY_HEX_REGEX = Regex("^[0-9a-f]{64}$")
        val CREATED_AT_REGEX = Regex("^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$")
    }

    private val noBackupDirectory = File(context.noBackupFilesDir, DIRECTORY)

    /** Encrypted identity envelope path. Exposed for on-device verification. */
    val blobFile: File = File(noBackupDirectory, BLOB_FILE)

    /** Non-secret identity metadata path. Exposed for on-device verification. */
    val metadataFile: File = File(noBackupDirectory, METADATA_FILE)

    private val blobTempFile = File(noBackupDirectory, BLOB_TEMP_FILE)
    private val metadataTempFile = File(noBackupDirectory, METADATA_TEMP_FILE)

    // ---------------------------------------------------------------- metadata

    fun hasMetadata(): Boolean = metadataFile.isFile

    fun hasBlob(): Boolean = blobFile.isFile && blobFile.length() > 0L

    /**
     * Reads and strictly validates the non-secret identity metadata.
     *
     * Returns `null` when no metadata file exists. Throws
     * [MetadataInvalidException] when the file exists but is not exactly the
     * production metadata document.
     */
    fun readMetadata(): IdentityMetadata? {
        if (!metadataFile.isFile) {
            return null
        }

        val text = try {
            metadataFile.readText(Charsets.UTF_8)
        } catch (_: Exception) {
            throw MetadataInvalidException("identity metadata could not be read")
        }

        val lines = text.split('\n').filter { it.isNotEmpty() }
        if (lines.size != 4 || lines[0] != METADATA_HEADER) {
            throw MetadataInvalidException("identity metadata is not in the supported format")
        }

        val publicKeyHex = lines[1].removePrefix("public_key=")
        if (!lines[1].startsWith("public_key=") || !PUBLIC_KEY_HEX_REGEX.matches(publicKeyHex)) {
            throw MetadataInvalidException("identity metadata has an invalid public key")
        }

        val algorithm = lines[2].removePrefix("algorithm=")
        if (!lines[2].startsWith("algorithm=") || algorithm != IDENTITY_ALGORITHM) {
            throw MetadataInvalidException("identity metadata has an unsupported algorithm")
        }

        val createdAt = lines[3].removePrefix("created_at=")
        if (!lines[3].startsWith("created_at=") ||
            createdAt.length > MAX_CREATED_AT_LENGTH ||
            !CREATED_AT_REGEX.matches(createdAt)
        ) {
            throw MetadataInvalidException("identity metadata has an invalid creation time")
        }

        return IdentityMetadata(
            publicKeyHex = publicKeyHex,
            algorithm = algorithm,
            createdAt = createdAt,
        )
    }

    /** Writes non-secret metadata atomically for a provisioned identity. */
    fun writeMetadata(publicKeyHex: String) {
        if (!PUBLIC_KEY_HEX_REGEX.matches(publicKeyHex)) {
            throw MetadataInvalidException("identity public key is invalid")
        }
        val now = SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss'Z'", Locale.US).apply {
            timeZone = TimeZone.getTimeZone("UTC")
        }.format(Date())

        val document = buildString {
            append(METADATA_HEADER)
            append('\n')
            append("public_key=")
            append(publicKeyHex)
            append('\n')
            append("algorithm=")
            append(IDENTITY_ALGORITHM)
            append('\n')
            append("created_at=")
            append(now)
            append('\n')
        }

        writeAtomically(metadataTempFile, metadataFile, document.toByteArray(Charsets.UTF_8))
    }

    fun deleteMetadata() {
        metadataFile.delete()
        metadataTempFile.delete()
    }

    // -------------------------------------------------------------------- blob

    /**
     * Wraps [seed] with the Keystore AES-256-GCM key and persists the envelope
     * atomically. The caller keeps ownership of [seed] and must clear it.
     */
    fun wrapAndPersist(seed: ByteArray, publicKeyHex: String) {
        if (seed.size != SEED_LENGTH) {
            throw IdentityStoreException("invalid identity seed length")
        }
        if (!PUBLIC_KEY_HEX_REGEX.matches(publicKeyHex)) {
            throw IdentityStoreException("invalid identity public key")
        }

        val header = buildHeader()
        val key = getOrCreateKeystoreKey()

        val iv: ByteArray
        val ciphertext: ByteArray
        try {
            val cipher = Cipher.getInstance("AES/GCM/NoPadding")
            cipher.init(Cipher.ENCRYPT_MODE, key)
            cipher.updateAAD(additionalAuthenticatedData(header, publicKeyHex))
            ciphertext = cipher.doFinal(seed)
            iv = cipher.iv
        } catch (_: GeneralSecurityException) {
            // Fixed, non-secret failure: no provider detail is surfaced.
            throw IdentityStoreException("identity could not be encrypted")
        }

        if (iv.size != IV_LENGTH || ciphertext.size != SEED_LENGTH + TAG_LENGTH) {
            throw IdentityStoreException("encrypted identity has an unexpected size")
        }

        val blob = ByteArrayOutputStream(BLOB_LENGTH).apply {
            write(header)
            write(iv)
            write(ciphertext)
        }.toByteArray()

        try {
            if (blob.size != BLOB_LENGTH) {
                throw IdentityStoreException("encrypted identity has an unexpected size")
            }
            writeAtomically(blobTempFile, blobFile, blob)
        } finally {
            blob.fill(0)
            ciphertext.fill(0)
        }
    }

    /**
     * Reads and authenticates the persisted envelope, returning the recovered
     * seed. The caller owns the returned array and must clear it.
     *
     * [publicKeyHex] must be the expected public identity: it is bound into the
     * AAD, so a mismatch fails authenticated decryption rather than returning
     * the wrong seed.
     */
    fun unwrapPersisted(publicKeyHex: String): ByteArray {
        if (!PUBLIC_KEY_HEX_REGEX.matches(publicKeyHex)) {
            throw MetadataInvalidException("identity public key is invalid")
        }
        if (!hasBlob()) {
            throw BlobMissingException("encrypted identity blob is missing")
        }

        val blob = try {
            blobFile.readBytes()
        } catch (_: Exception) {
            throw BlobCorruptException("encrypted identity blob could not be read")
        }

        try {
            if (blob.size != BLOB_LENGTH) {
                throw BlobCorruptException("encrypted identity blob is malformed")
            }
            for (index in MAGIC.indices) {
                if (blob[index] != MAGIC[index]) {
                    throw BlobCorruptException("encrypted identity header is invalid")
                }
            }
            val version = blob[4].toInt() and 0xff
            if (version != ENVELOPE_VERSION) {
                throw BlobUnsupportedException("encrypted identity version is unsupported")
            }
            val algorithm = blob[5].toInt() and 0xff
            if (algorithm != ALGORITHM_AES_256_GCM) {
                throw BlobUnsupportedException("encrypted identity algorithm is unsupported")
            }
            if ((blob[6].toInt() and 0xff) != IV_LENGTH ||
                (blob[7].toInt() and 0xff) != SEED_LENGTH
            ) {
                throw BlobCorruptException("encrypted identity header is invalid")
            }

            val header = blob.copyOfRange(0, HEADER_LENGTH)
            val iv = blob.copyOfRange(HEADER_LENGTH, HEADER_LENGTH + IV_LENGTH)
            val ciphertext = blob.copyOfRange(HEADER_LENGTH + IV_LENGTH, blob.size)

            val key = getExistingKeystoreKey()
            val seed = try {
                val cipher = Cipher.getInstance("AES/GCM/NoPadding")
                cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(TAG_LENGTH * 8, iv))
                cipher.updateAAD(additionalAuthenticatedData(header, publicKeyHex))
                cipher.doFinal(ciphertext)
            } catch (_: AEADBadTagException) {
                throw BlobCorruptException("encrypted identity authentication failed")
            } catch (_: KeyStoreException) {
                throw KeystoreKeyUnavailableException("identity wrapping key is unavailable")
            } catch (_: UnrecoverableKeyException) {
                throw KeystoreKeyUnavailableException("identity wrapping key is unavailable")
            } catch (_: GeneralSecurityException) {
                throw BlobCorruptException("encrypted identity could not be decrypted")
            }

            if (seed.size != SEED_LENGTH) {
                seed.fill(0)
                throw BlobCorruptException("decrypted identity has an invalid length")
            }
            return seed
        } finally {
            blob.fill(0)
        }
    }

    fun deleteBlob() {
        blobFile.delete()
        blobTempFile.delete()
    }

    // ---------------------------------------------------------------- keystore

    /** Deletes the Keystore wrapping key. Used only by an explicit identity reset. */
    fun deleteKeystoreKey() {
        val keyStore = KeyStore.getInstance(KEYSTORE_PROVIDER)
        keyStore.load(null)
        if (keyStore.containsAlias(KEY_ALIAS)) {
            keyStore.deleteEntry(KEY_ALIAS)
        }
    }

    private fun getOrCreateKeystoreKey(): SecretKey {
        val keyStore = try {
            KeyStore.getInstance(KEYSTORE_PROVIDER).apply { load(null) }
        } catch (_: GeneralSecurityException) {
            throw KeystoreKeyUnavailableException("identity keystore is unavailable")
        }

        if (!keyStore.containsAlias(KEY_ALIAS)) {
            try {
                KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE_PROVIDER).apply {
                    init(
                        KeyGenParameterSpec.Builder(
                            KEY_ALIAS,
                            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
                        )
                            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                            .setKeySize(256)
                            .setRandomizedEncryptionRequired(true)
                            .build(),
                    )
                }.generateKey()
            } catch (_: GeneralSecurityException) {
                throw KeystoreKeyUnavailableException("identity wrapping key could not be created")
            }
        }

        return getExistingKeystoreKey()
    }

    private fun getExistingKeystoreKey(): SecretKey {
        val keyStore = try {
            KeyStore.getInstance(KEYSTORE_PROVIDER).apply { load(null) }
        } catch (_: GeneralSecurityException) {
            throw KeystoreKeyUnavailableException("identity keystore is unavailable")
        }

        if (!keyStore.containsAlias(KEY_ALIAS)) {
            throw KeystoreKeyUnavailableException("identity wrapping key is unavailable")
        }

        return try {
            keyStore.getKey(KEY_ALIAS, null) as? SecretKey
                ?: throw KeystoreKeyUnavailableException("identity wrapping key is unavailable")
        } catch (_: UnrecoverableKeyException) {
            throw KeystoreKeyUnavailableException("identity wrapping key is unavailable")
        } catch (_: KeyStoreException) {
            throw KeystoreKeyUnavailableException("identity wrapping key is unavailable")
        }
    }

    // ----------------------------------------------------------------- helpers

    private fun buildHeader(): ByteArray {
        val header = ByteArray(HEADER_LENGTH)
        MAGIC.copyInto(header, 0)
        header[4] = ENVELOPE_VERSION.toByte()
        header[5] = ALGORITHM_AES_256_GCM.toByte()
        header[6] = IV_LENGTH.toByte()
        header[7] = SEED_LENGTH.toByte()
        return header
    }

    private fun additionalAuthenticatedData(
        header: ByteArray,
        publicKeyHex: String,
    ): ByteArray {
        val aad = ByteArray(header.size + publicKeyHex.length)
        header.copyInto(aad, 0)
        publicKeyHex.toByteArray(Charsets.US_ASCII).copyInto(aad, header.size)
        return aad
    }

    private fun writeAtomically(tempFile: File, targetFile: File, bytes: ByteArray) {
        try {
            if (!noBackupDirectory.isDirectory && !noBackupDirectory.mkdirs()) {
                throw IdentityStoreException("identity storage directory is unavailable")
            }
            FileOutputStream(tempFile, false).use { stream ->
                stream.write(bytes)
                stream.flush()
                stream.fd.sync()
            }
            if (!tempFile.renameTo(targetFile)) {
                throw IdentityStoreException("identity could not be stored")
            }
        } catch (error: IdentityStoreException) {
            throw error
        } catch (_: Exception) {
            throw IdentityStoreException("identity could not be stored")
        } finally {
            tempFile.delete()
        }
    }
}

/** Lowercase-hex SHA-256 fingerprint of a 32-byte public identity. */
fun publicKeyFingerprintHex(publicKeyHex: String): String {
    val bytes = publicKeyHex.chunked(2).map { it.toInt(16).toByte() }.toByteArray()
    return MessageDigest.getInstance("SHA-256")
        .digest(bytes)
        .joinToString(separator = "") { byte -> String.format(Locale.US, "%02x", byte.toInt() and 0xff) }
}
